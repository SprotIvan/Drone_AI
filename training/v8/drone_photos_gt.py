LEFT_OUT = {16: "no drone visible (parking lot; the inset shows a man with a tripod)",
            43: "an object in the man's hand that may be a drone - can not tell (a second, flying drone is clear)"}


def main():
    names = sorted(p.name for p in (SRC / "images").iterdir() if p.suffix.lower() in (".jpg", ".jpeg", ".png"))
    if DST.exists():
        shutil.rmtree(DST)
    (DST / "images").mkdir(parents=True)
    (DST / "labels").mkdir(parents=True)
    n_img = n_box = 0
    for i, name in enumerate(names):
        if i in LEFT_OUT or i not in E:
            continue
        with Image.open(SRC / "images" / name) as im:
            w, h = im.size
        k = 480 / max(w, h)
        lines = []
        for x1, y1, x2, y2 in E[i]:
            x1, y1, x2, y2 = max(0, x1 / k), max(0, y1 / k), min(w, x2 / k), min(h, y2 / k)
            lines.append(f"0 {(x1 + x2) / 2 / w:.6f} {(y1 + y2) / 2 / h:.6f} {(x2 - x1) / w:.6f} {(y2 - y1) / h:.6f}")
        shutil.copy2(SRC / "images" / name, DST / "images" / name)
        (DST / "labels" / (Path(name).stem + ".txt")).write_text("\n".join(lines) + "\n")
        n_img += 1
        n_box += len(lines)
    (DST / "left_out.json").write_text(json.dumps({names[i]: r for i, r in LEFT_OUT.items()}, indent=1))
    print(f"{n_img} images, {n_box} drones -> {DST}; left out {len(LEFT_OUT)}; "
          f"not yet decided {len(names) - n_img - len(LEFT_OUT)}")


if __name__ == "__main__":
    main()
